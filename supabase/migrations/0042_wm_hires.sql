-- (2026-10-12 이식: 사용자의 친구가 만들어 보낸 '알바 채용·면접비' 메뉴. 받은 파일 이름은 0040이었으나 그 번호를 이미 써서 0042로 넣음)
-- ═══════════════════════════════════════════════════════════════
-- 알바 채용·면접비 (wm-hire 함수 전용)
--
-- 보안 모델: 근무관리(0005)와 같음 — RLS 켜고 정책 없음 → service_role(Edge Function)만 접근.
--   db 프록시에 이 테이블을 절대 노출하지 말 것.
-- 주민번호·계좌번호는 평문 저장 금지(개인정보보호법 §24-2, 시행령 §21-2):
--   *_enc = wm-hire 함수가 AES-256-GCM으로 암호화한 값('v1.' + base64(iv||암호문)),
--   rrn_hash = HMAC-SHA256(주민번호 숫자) — 같은 사람 중복 등록 막는 용도(복호화 불가).
--   키는 Supabase secret HIRE_ENC_KEY. 키를 잃으면 암호문을 영영 못 푼다 → 별도 보관.
-- ═══════════════════════════════════════════════════════════════

create table if not exists wm_hires (
  id              integer primary key generated by default as identity,
  name            text not null,
  phone           text not null,                       -- '010-1234-5678'
  rrn_enc         text,                                -- 주민번호 암호문 (없으면 미입력)
  rrn_hash        text unique,                         -- 중복 방지
  birth           date,                                -- 주민번호에서 뽑은 생년월일 (만 나이 경고·채용 시 생일 연동)
  bank_name       text,
  account_enc     text,                                -- 계좌번호 암호문
  bank_holder     text,
  kind            text not null default 'applicant' check (kind in ('applicant','daily')),  -- 채용 지원자 / 일일알바
  status          text not null default 'interview' check (status in ('interview','hired','rejected')),
  interview_date  date,
  memo            text,
  employee_id     integer references wm_employees(id), -- 채용 처리 시 근무관리 알바로 연결
  created_by      text,                                -- app_users.name
  created_at      timestamptz not null default now()
);

-- 지급 기록(면접비·시범근무·일일알바 일당). 금액은 서버(calc.ts)가 계산해 저장 — 화면 미리보기는 참고용.
create table if not exists wm_hire_pays (
  id           integer primary key generated by default as identity,
  hire_id      integer not null references wm_hires(id) on delete cascade,
  work_date    date not null,
  start_time   text check (start_time ~ '^\d{2}:\d{2}$'),
  end_time     text check (end_time   ~ '^\d{2}:\d{2}$'),
  minutes      integer not null default 0 check (minutes >= 0),
  hourly_rate  integer not null default 0 check (hourly_rate >= 0),
  fixed_amount integer check (fixed_amount >= 0),     -- 있으면 시급 대신 이 금액 (정액 면접비)
  emp_ins      boolean not null default false,        -- 고용보험 0.9% 공제 여부
  gross        integer not null,                      -- 지급액(세전)
  income_tax   integer not null,                      -- 사업소득세 = ROUNDDOWN(세전×3%, -1)
  local_tax    integer not null,                      -- 지방소득세 = ROUNDDOWN(세전×0.3%, -1)
  emp_ins_amt  integer not null,
  net          integer not null,                      -- 실지급액
  paid_on      date,                                  -- 입금한 날 (null = 미지급)
  note         text,
  created_by   text,
  created_at   timestamptz not null default now()
);
create index if not exists wm_hire_pays_hire on wm_hire_pays(hire_id);
create index if not exists wm_hire_pays_date on wm_hire_pays(work_date);

alter table wm_hires     enable row level security;
alter table wm_hire_pays enable row level security;
