-- 근무 관리 — '77사이즈 촬영' 기입(2026-10-27 사용자 요청)
--   지정한 알바가 키오스크(PIN 확인 뒤)에서 촬영 일자·종류(사진/라방)·상품명을 적고, 관리자는 근무 관리 › 77사이즈 촬영에서 본다.
--   누가 적을 수 있는지 = wm_employees.shoot_log(관리자가 근무 관리에서 켜고 끔).
alter table public.wm_employees add column if not exists shoot_log boolean not null default false;

create table if not exists public.wm_shoots (
  id          bigint generated by default as identity primary key,
  employee_id integer not null references public.wm_employees(id),
  shoot_date  date not null,
  kind        text not null check (kind in ('photo', 'live')),   -- 사진 / 라방
  product     text not null check (char_length(product) between 1 and 200),
  created_at  timestamptz not null default now()
);
create index if not exists wm_shoots_date_idx on public.wm_shoots (shoot_date desc);
alter table public.wm_shoots enable row level security;   -- 정책 없음 — 서버(service_role)만
