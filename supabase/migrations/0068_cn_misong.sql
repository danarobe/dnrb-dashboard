-- 중국 사입/제작 관리 › 미송 확인 (2026-10-26 사용자 요청)
--   "중국에서 받은 미송 엑셀을 올리면 올린 날짜·며칠 기준인지, 상품 사진·품번·쇼핑몰 상품명·미송 항목과 수량, 항목별 입고 날짜를 보여 줘.
--    단가·합계는 안 보이게. 새 파일을 올리면 직전 파일만 남기고 그 전 파일은 지워도 된다."
--   화면이 엑셀을 읽어 품번 묶음(items)으로 보낸다 — 단가(F)·합계(G)는 읽지도 보내지도 않는다.
--   items = [{sname, store, rows:[{color, size, qty}], notes:[{text}], checks:[text]}], thumbs = {품번: 160px JPEG data URL}
--   서버는 올릴 때마다 최근 2개(지금 + 직전)만 남기고 그 전 것은 지운다.
create table if not exists public.cn_misong (
  id               bigint generated by default as identity primary key,
  file_name        text,
  base_date        date,                  -- 엑셀 머리글 'MM/DD기준'(없으면 올린 날)
  base_label       text,                  -- 머리글 원문(예: '10/25기준')
  items            jsonb not null,
  thumbs           jsonb,
  uploaded_by      text,
  uploaded_by_name text,
  uploaded_at      timestamptz not null default now()
);
alter table public.cn_misong enable row level security;   -- 정책 없음 — 서버(service_role)만
