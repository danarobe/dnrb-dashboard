-- 중국 사입/제작 관리 — '불량 기록' 소메뉴(2026-10-26 사용자 요청)
--   상품·옵션별 불량 수량을 한 줄씩 적는다(입고 차수는 골라도 되고 비워도 됨). 불량률 = 불량 ÷ 검수 완료 차수의 실입고.
--   입고 검수의 '불량'(cn_lines.qty_defect) 칸은 같은 날 화면에서 없앰(적힌 값 0건).
create table if not exists public.cn_defects (
  id              bigint generated by default as identity primary key,
  sname           text not null,                                  -- 사입상품명(품번)
  color           text,
  size            text,
  shipment_id     bigint references public.cn_shipments(id) on delete set null,   -- 어느 입고에서 나온 불량인지(모르면 비움)
  qty             integer not null check (qty > 0 and qty <= 100000),
  found_on        date not null default current_date,             -- 불량을 발견한 날
  note            text,
  created_by      text,
  created_by_name text,
  created_at      timestamptz not null default now()
);
create index if not exists cn_defects_sname_idx on public.cn_defects (sname);
alter table public.cn_defects enable row level security;   -- 정책 없음 — 서버(service_role)만
