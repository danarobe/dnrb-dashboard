-- 중국 사입/제작 관리 — 주문서 다시 (2026-10-19 사용자 요청: "주문서 수량을 표기 안 하니 언제 얼마나 주문했는지 알 수 없다").
--   표의 수량 = 주문 | 중국출고(입고 엑셀 E열) | 실입고(실제 수량) | 잔여(주문 − 중국출고) | 차이(중국출고 − 실입고) | 입고중불량.
--   cn_orders = 주문서 1건(엑셀 파일 1개), cn_order_lines = 옵션별 주문 수량(품번·색상·사이즈·수량만 — 단가 없음).
--   cn_shipments.order_id = 그 입고가 어느 주문서의 것인지(주문서를 지우면 null). 0049(같은 날 만들었다 0050에서 지움)와 같은 모양에서 '직접 정리(closed)' 칸만 뺐다.
create table if not exists cn_orders (
  id              bigint primary key generated by default as identity,
  title           text not null,
  order_date      date,
  file_name       text,
  note            text,
  created_by      text,
  created_by_name text,
  created_at      timestamptz not null default now()
);
create table if not exists cn_order_lines (
  id       bigint primary key generated by default as identity,
  order_id bigint not null references cn_orders(id) on delete cascade,
  seq      integer not null default 0,
  sheet    text,
  sname    text not null,
  color    text,
  size     text,
  qty      integer not null check (qty >= 0)
);
create index if not exists cn_order_lines_order on cn_order_lines(order_id);
alter table cn_shipments add column if not exists order_id bigint references cn_orders(id) on delete set null;
alter table cn_orders enable row level security;
alter table cn_order_lines enable row level security;
