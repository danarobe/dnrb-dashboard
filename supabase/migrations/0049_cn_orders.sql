-- 중국 사입 관리 — 주문서 (2026-10-14 사용자 요청: "주문서도 첨부해서 주문서 수량과 비교하는 게 정확할 것 같다. 지금 등록된 1차·2차 2건은 주문서 1건에 대한 수량").
--   cn_orders = 주문서 1건(엑셀 파일 1개 — 시트가 여러 장이어도 한 건), cn_order_lines = 옵션별 주문 수량.
--   주문서에서는 **품번·색상·사이즈·수량만** 쓴다(사용자 지정 — 단가는 저장하지 않음. 그래서 MD·물류팀에게도 그대로 보인다). 사진은 cn_thumbs에(이미 있는 품번은 그대로).
--   cn_shipments.order_id = 그 입고가 어느 주문서의 것인지(주문서를 지우면 null). 비교 = 주문 수량 − 그 주문서에 연결된 입고들의 전달 수량 합(화면 cnOrderCalc).
--   cn_order_lines.closed = 아직 안 들어온 수량을 사람이 정리: 'in'(들어옴으로 처리) | 'cancel'(받지 않기로 함).
--   쓰기는 cafe24-analytics cn_order_upload·cn_order(관리자·MD) / cn_order_close(관리자·MD·물류팀)만.
create table if not exists cn_orders (
  id              bigint primary key generated by default as identity,
  title           text not null,
  order_date      date,
  file_name       text,
  note            text,
  created_by      text,
  created_by_name text,
  created_at      timestamptz not null default now()
);
create table if not exists cn_order_lines (
  id             bigint primary key generated by default as identity,
  order_id       bigint not null references cn_orders(id) on delete cascade,
  seq            integer not null default 0,
  sheet          text,
  sname          text not null,
  color          text,
  size           text,
  qty            integer not null check (qty >= 0),
  closed         text check (closed in ('in', 'cancel')),
  closed_note    text,
  closed_by_name text,
  closed_at      timestamptz
);
create index if not exists cn_order_lines_order on cn_order_lines(order_id);
alter table cn_shipments add column if not exists order_id bigint references cn_orders(id) on delete set null;
alter table cn_orders enable row level security;
alter table cn_order_lines enable row level security;
