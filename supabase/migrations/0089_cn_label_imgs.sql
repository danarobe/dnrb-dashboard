-- 중국 사입/제작 관리 › 입고 검수 — 상품별 라벨 사진 (2026-11-24 사용자 요청 — "상품들에 라벨 이미지를 첨부할 수 있게, 마우스를 올리면 이미지를 볼 수 있게").
--   사입상품명(sname)마다 여러 장(서버가 6장까지). 사진은 브라우저에서 긴 변 1280px JPEG로 줄여 data URL로 보낸다(원본은 올리지 않음).
--   목록(cn_list)에는 번호·올린 사람·시각만 싣고, 사진은 마우스를 올릴 때 cn_label_imgs {get}으로 받는다.
--   쓰기·지우기 = 관리자·MD(cafe24-analytics가 확인), 보기 = 중국 사입 메뉴를 보는 사람(CS 보기 전용 포함).
create table if not exists public.cn_label_imgs (
  id        bigint primary key generated by default as identity,
  sname     text not null,
  img       text not null,            -- data:image/jpeg;base64,…
  w         integer,
  h         integer,
  by_name   text,
  at        timestamptz not null default now()
);
create index if not exists cn_label_imgs_sname on public.cn_label_imgs(sname);
alter table public.cn_label_imgs enable row level security;   -- 정책 없음 — 서버(cafe24-analytics)만
revoke all on table public.cn_label_imgs from anon, authenticated;
