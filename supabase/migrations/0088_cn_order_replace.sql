-- 중국 사입/제작 관리 › 주문서 [파일 바꾸기] (2026-11-23 사용자 요청 — "업로드한 주문서 엑셀을 나중에 바꿀 수 있게, 지우고 다시 올리는 것과 같은 효과").
--   이미 올린 주문서의 옵션 줄을 새 파일 내용으로 한 번에 바꾼다(이름·주문일·메모·등록한 사람은 그대로).
--   한 트랜잭션: 예전 줄을 기록(cn_order_replace_log)에 남기고 → 지우고 → 새 줄을 넣는다. 중간에 실패하면 아무것도 안 바뀜.
alter table public.cn_orders add column if not exists replaced_at timestamptz;
alter table public.cn_orders add column if not exists replaced_by_name text;

create table if not exists public.cn_order_replace_log (
  id            bigint primary key generated by default as identity,
  order_id      bigint not null references public.cn_orders(id) on delete cascade,
  old_file_name text,
  new_file_name text,
  old_count     integer not null,
  new_count     integer not null,
  old_qty       integer not null,
  new_qty       integer not null,
  old_lines     jsonb not null,   -- 바꾸기 전 줄 전부(되돌릴 때 쓸 수 있게)
  by_id         text,
  by_name       text,
  at            timestamptz not null default now()
);
create index if not exists cn_order_replace_log_order on public.cn_order_replace_log(order_id);
alter table public.cn_order_replace_log enable row level security;   -- 정책 없음 — 서버(cafe24-analytics)만

create or replace function public.cn_order_replace_lines(p_order_id bigint, p_rows jsonb, p_file_name text, p_by_id text, p_by_name text)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  v_old_file text;
  v_old jsonb;
  v_old_count integer;
  v_old_qty integer;
  v_new_count integer;
  v_new_qty integer;
begin
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
    raise exception 'rows_empty' using errcode = '22023';
  end if;
  select file_name into v_old_file from cn_orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found' using errcode = 'P0002'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('seq', seq, 'sheet', sheet, 'sname', sname, 'color', color, 'size', size, 'qty', qty) order by seq, id), '[]'::jsonb),
         count(*), coalesce(sum(qty), 0)
    into v_old, v_old_count, v_old_qty
    from cn_order_lines where order_id = p_order_id;
  if v_old_count = 0 then raise exception 'order_has_no_lines' using errcode = '22023'; end if;   -- 일자만 등록한 주문서는 [주문서 올리기]로
  delete from cn_order_lines where order_id = p_order_id;
  insert into cn_order_lines (order_id, seq, sheet, sname, color, size, qty)
    select p_order_id, (r->>'seq')::integer, nullif(r->>'sheet', ''), r->>'sname', nullif(r->>'color', ''), nullif(r->>'size', ''), (r->>'qty')::integer
      from jsonb_array_elements(p_rows) as r;
  select count(*), coalesce(sum(qty), 0) into v_new_count, v_new_qty from cn_order_lines where order_id = p_order_id;
  insert into cn_order_replace_log (order_id, old_file_name, new_file_name, old_count, new_count, old_qty, new_qty, old_lines, by_id, by_name)
    values (p_order_id, v_old_file, p_file_name, v_old_count, v_new_count, v_old_qty, v_new_qty, v_old, p_by_id, p_by_name);
  update cn_orders set file_name = coalesce(nullif(p_file_name, ''), file_name), replaced_at = now(), replaced_by_name = p_by_name where id = p_order_id;
  return jsonb_build_object('old_count', v_old_count, 'new_count', v_new_count, 'old_qty', v_old_qty, 'new_qty', v_new_qty);
end;
$$;
revoke all on function public.cn_order_replace_lines(bigint, jsonb, text, text, text) from public, anon, authenticated;
grant execute on function public.cn_order_replace_lines(bigint, jsonb, text, text, text) to service_role;
