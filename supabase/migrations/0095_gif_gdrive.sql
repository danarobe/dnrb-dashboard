-- GIF 메이커 › [구글 드라이브에 저장] (2026-11-26 사용자 요청 — "구글 계정 연결, 대표(관리자)만")
--   gif_gdrive     : 연결한 구글 계정 1개(줄 하나). 연결 증표(refresh token)는 암호화한 값만 둔다. 서버(gif 함수)만 읽고 쓴다.
--   gif_gdrive_log : 누가 어느 폴더에 무엇을 저장했는지.
create table if not exists gif_gdrive (
  id           text primary key default 'main' check (id = 'main'),
  refresh_enc  text not null,
  email        text not null default '',
  by_id        text,
  by_name      text not null default '',
  at           timestamptz not null default now()
);
create table if not exists gif_gdrive_log (
  id         bigint primary key generated by default as identity,
  by_id      text,
  by_name    text not null default '',
  folder_id  text not null,
  file_id    text not null,
  name       text not null,
  bytes      integer not null,
  replaced   boolean not null default false,
  at         timestamptz not null default now()
);
alter table gif_gdrive enable row level security;
alter table gif_gdrive_log enable row level security;
revoke all on gif_gdrive, gif_gdrive_log from anon, authenticated;
