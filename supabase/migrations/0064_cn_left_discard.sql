-- 중국 사입/제작 관리 — 미출고(F열) 다시 + 폐기 (2026-10-23 사용자 요청)
--   "주문 수량 − 출고 서류의 출고 수량 − 미출고 수량 = 0이 되어야 한다. 미출고(F열)가 잔여 수량, '출완' = 더 나올 수량 없음.
--    원단에 따라 주문보다 덜 나오는 품목은 나머지를 '폐기'로 없앨 수 있게."
--   ① cn_lines.qty_left(이미 있는 칸 — 2026-10-14부터 비워 두던 것)를 다시 쓴다: F열 숫자, '출완' = 0, 빈칸 = null.
--   ② 출고(E)는 비었는데 미출고(F)만 적힌 줄(예: '26K07 深蓝곤 · 출고 없음 · 미출고 30')은 입고 줄로 만들지 않고 입고 건에 따로 담는다
--      (입고 검수에 출고 0 줄이 생기지 않게): [{sname, color, size, left}]
alter table public.cn_shipments add column if not exists left_extra jsonb;

-- ③ 폐기 = 주문했지만 더 나오지 않을(받지 않을) 수량. 잔여 = 주문 − 중국출고 − 폐기. 지우면(되돌리기) 다시 잔여로 돌아온다.
create table if not exists public.cn_discards (
  id              bigint generated by default as identity primary key,
  sname           text not null,                                  -- 사입상품명(품번)
  color           text,
  size            text,
  qty             integer not null check (qty > 0 and qty <= 1000000),
  note            text,
  created_by      text,
  created_by_name text,
  created_at      timestamptz not null default now()
);
create index if not exists cn_discards_sname_idx on public.cn_discards (sname);
alter table public.cn_discards enable row level security;   -- 정책 없음 — 서버(service_role)만
