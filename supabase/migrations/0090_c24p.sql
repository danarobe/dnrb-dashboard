-- 상품 등록 전용 카페24 앱(cafe24-product 함수) — 2026-11-25 사용자 결정
--   토큰은 api_tokens provider='cafe24p'(기존 'cafe24'와 다른 앱). 아래 세 표는 그 함수만 쓴다(RLS 켬·정책 없음·권한 회수, db 프록시 미등록).
-- ① 이 시스템이 카페24에 만든 상품 — 상품번호가 여기 있는 상품만 수정할 수 있다(기존 상품 보호)
create table if not exists public.c24p_registry (
  npm_id      text primary key,            -- 상품 관리 시스템 products.id
  product_no  integer unique,              -- 카페24 상품번호 (등록 성공 뒤 채움)
  state       text not null default 'pending' check (state in ('pending','created','failed')),
  steps       jsonb not null default '{}'::jsonb,   -- 단계별 결과(분류·진열·사진·아이콘 …)
  by_name     text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
-- ② 카페24로 보낸 쓰기 기록(본문·사진은 저장하지 않음)
create table if not exists public.c24p_log (
  id          bigint primary key generated by default as identity,
  at          timestamptz not null default now(),
  by_name     text,
  npm_id      text,
  method      text not null,
  path        text not null,
  status      integer,
  ok          boolean,
  note        text
);
create index if not exists c24p_log_at on public.c24p_log(at desc);
-- ③ 연동 상태(권한 목록·마지막 자동 갱신·연동한 사람)
create table if not exists public.c24p_state (
  k   text primary key,
  v   jsonb not null default '{}'::jsonb,
  at  timestamptz not null default now()
);
alter table public.c24p_registry enable row level security;
alter table public.c24p_log enable row level security;
alter table public.c24p_state enable row level security;
revoke all on table public.c24p_registry, public.c24p_log, public.c24p_state from anon, authenticated;
