-- 중국 사입/제작 관리 — '원>달러>위안 환전' 소메뉴 (2026-10-22 사용자 요청)
--   원→달러 환전(은행 바로환전 내역 엑셀을 붙여넣어 추가) → 달러를 송금(포워딩 은행이 위안으로 바꿔 에이전시 통장에 입금)
--   → 에이전시 위안 통장(수수료: 포워딩 100위안·에이전시 0.003% 뺀 실수령)을 입고(출고 서류 총 합계)가 선입선출로 꺼내 쓴다.
--   서버 cafe24-analytics cnFxModel이 입고마다 '1위안 원가'를 계산하고, 실질 단가·종합 판매 데이터 마진율·상품관리 내보내기가 그 값을 쓴다.
create table if not exists public.cn_fx_buys (            -- 원→달러 환전(바로환전 체결 내역)
  id              bigint generated by default as identity primary key,
  order_no        text not null unique,                   -- 은행 주문번호(같은 내역을 두 번 붙여넣어도 한 번만)
  traded_at       timestamptz not null,                   -- 체결일시
  usd             numeric(14,2) not null check (usd > 0), -- 거래금액(달러)
  krw             bigint not null check (krw > 0),        -- 체결상대금액(원)
  rate            numeric(12,4) not null check (rate > 0),-- 체결환율(원/달러)
  created_by_name text,
  created_at      timestamptz not null default now()
);
create table if not exists public.cn_remits (             -- 달러→위안 송금(에이전시 통장 실수령)
  id              bigint generated by default as identity primary key,
  remit_date      date not null,
  usd             numeric(14,2) not null check (usd > 0), -- 보낸 달러
  cny             numeric(14,2) not null check (cny > 0), -- 에이전시 통장에 들어온 위안(포워딩 100위안·에이전시 0.003% 뺀 값 — 사용자 입력)
  memo            text,
  created_by_name text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
-- 출고 서류의 합계 블록(위안): {goods 물건값 합계, agency 에이전시 10%, items[{name,cny}] 경비·특송+택배 등, total 총 합계, src}
alter table public.cn_shipments add column if not exists doc jsonb;
alter table public.cn_fx_buys enable row level security;
alter table public.cn_remits enable row level security;
